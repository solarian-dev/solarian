"""The files Solarian writes for coding agents into a project or a plugin.

``AGENTS.md``, ``CLAUDE.md`` and the skills under ``.agents/skills`` and
``.claude/skills`` belong to Solarian: ``sync_agent_files`` regenerates them for
the installed Solarian and plugins, and ``.agents/solarian-managed.json`` records
what it wrote so a later sync can tell its own files from ones a person edited.
``.agents/NOTES.md`` belongs to the user and is only ever created.
"""

from __future__ import annotations

import hashlib
import importlib
import importlib.metadata
import importlib.util
import json
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import unquote, urlparse

from jinja2 import Environment, FileSystemLoader, StrictUndefined

import solarian

TEMPLATES = Path(solarian.__file__).parent / "templates" / "agent"

MANIFEST = ".agents/solarian-managed.json"
NOTES = ".agents/NOTES.md"
#: Project-level skill folders: Cursor and Codex read .agents/skills, Claude Code .claude/skills.
SKILL_DIRS = (".agents/skills", ".claude/skills")
#: User-level skill folders for ``solarian agent install``, by target name.
USER_SKILL_DIRS = {
    "agents": Path.home() / ".agents" / "skills",
    "claude": Path.home() / ".claude" / "skills",
    "cursor": Path.home() / ".cursor" / "skills",
}
BOOTSTRAP_SKILL = "solarian"

STAMP = "<!-- generated by solarian {version}; do not edit; project notes: .agents/NOTES.md -->"
STAMP_RE = re.compile(r"<!-- (?:generated|installed) by solarian (\S+?);")

KINDS = ("project", "plugin")


def solarian_version() -> str:
    try:
        return importlib.metadata.version("solarian")
    except importlib.metadata.PackageNotFoundError:
        return "unknown"


def stamp_version(text: str) -> str | None:
    """The Solarian version that wrote a generated file, from its stamp."""
    match = STAMP_RE.search(text)
    return match[1] if match else None


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _pyproject_text(root: Path) -> str:
    path = root / "pyproject.toml"
    return path.read_text(encoding="utf-8") if path.is_file() else ""


def pyproject_name(root: Path) -> str:
    match = re.search(r'^name\s*=\s*"([^"]+)"', _pyproject_text(root), re.M)
    return match[1] if match else root.name


def _entry_point_groups(pyproject: str) -> list[str]:
    """``modules``, ``skills``, ... for each ``[project.entry-points."solarian.<group>"]`` table."""
    return re.findall(r'^\[project\.entry-points\."solarian\.([a-z_]+)"\]', pyproject, re.M)


def detect_kind(root: Path) -> str | None:
    """``plugin`` when the pyproject declares Solarian entry points, ``project`` otherwise."""
    pyproject = _pyproject_text(root)
    if not pyproject:
        return None
    return "plugin" if _entry_point_groups(pyproject) else "project"


def frontmatter(text: str) -> dict[str, str]:
    """The ``key: value`` lines between a SKILL.md's leading ``---`` fences."""
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not match:
        return {}
    fields = {}
    for line in match[1].split("\n"):
        key, sep, value = line.partition(":")
        if sep and not line.startswith((" ", "\t")):
            fields[key.strip()] = value.strip().strip("\"'")
    return fields


def _rename_skill(text: str, name: str) -> str:
    return re.sub(r"^(---\n(?:.*\n)*?)name:[^\n]*", rf"\g<1>name: {name}", text, count=1)


# ── Installed plugins ─────────────────────────────────────────────────


@dataclass(frozen=True)
class PluginAgent:
    """What an installed plugin tells agents: its summary, and ``<package>/agent/`` if it ships one."""

    dist: str
    short: str
    summary: str
    groups: tuple[str, ...]
    section: str
    skills: tuple[Path, ...]


def _package_dir(dist: importlib.metadata.Distribution, package: str) -> Path | None:
    spec = importlib.util.find_spec(package)
    if spec is not None and spec.submodule_search_locations:
        return Path(next(iter(spec.submodule_search_locations)))
    # An editable install made after this process started is not on sys.path
    # yet; its direct_url.json (PEP 610) still says where the source is.
    raw = dist.read_text("direct_url.json")
    if not raw:
        return None
    url = urlparse(json.loads(raw).get("url", ""))
    if url.scheme != "file":
        return None
    source = Path(unquote(url.path))
    return next((d for d in (source / package, source / "src" / package) if d.is_dir()), None)


def installed_plugins() -> list[PluginAgent]:
    """Every installed distribution that registers Solarian entry points, by name."""
    importlib.invalidate_caches()
    plugins: dict[str, PluginAgent] = {}
    for dist in importlib.metadata.distributions():
        name = dist.metadata["Name"]
        if not name or _canonical(name) == "solarian" or _canonical(name) in plugins:
            continue
        eps = [ep for ep in dist.entry_points if ep.group.startswith("solarian.")]
        if not eps:
            continue
        section, skills = "", ()
        for package in sorted({ep.value.split(":")[0].split(".")[0] for ep in eps}):
            package_dir = _package_dir(dist, package)
            if package_dir is None:
                continue
            notes = package_dir / "agent" / "AGENTS.md"
            if notes.is_file():
                section = re.sub(r"<!--.*?-->\n?", "", notes.read_text(encoding="utf-8"), flags=re.S)
                section = re.sub(r"\n{3,}", "\n\n", section).strip()
            # skills/<name>/SKILL.md is the layout plugins used before agent/.
            skills = tuple(sorted(p.parent for pattern in ("agent/skills/*/SKILL.md", "skills/*/SKILL.md")
                                  for p in package_dir.glob(pattern)))
            if section or skills:
                break
        dist_name = _canonical(name)
        plugins[dist_name] = PluginAgent(
            dist=dist_name,
            short=dist_name.removeprefix("solarian-"),
            summary=dist.metadata["Summary"] or "",
            groups=tuple(sorted({ep.group.removeprefix("solarian.") for ep in eps})),
            section=section,
            skills=skills,
        )
    return [plugins[name] for name in sorted(plugins)]


# ── What a sync writes ────────────────────────────────────────────────


def _environment() -> Environment:
    return Environment(
        loader=FileSystemLoader(str(TEMPLATES)),
        undefined=StrictUndefined,
        keep_trailing_newline=True,
        trim_blocks=True,
        lstrip_blocks=True,
    )


def _skill_files(skill_dir: Path, name: str, render) -> dict[str, bytes]:
    """``{path inside the skill: content}``, SKILL.md rendered and renamed to *name*."""
    files = {}
    for path in sorted(p for p in skill_dir.rglob("*") if p.is_file() and "__pycache__" not in p.parts):
        rel = path.relative_to(skill_dir).as_posix()
        if rel == "SKILL.md":
            files[rel] = _rename_skill(render(path.read_text(encoding="utf-8")), name).encode()
        else:
            files[rel] = path.read_bytes()
    return files


def desired_files(root: Path, kind: str) -> dict[str, bytes]:
    """Every managed file a sync of *root* writes, by path relative to *root*."""
    env = _environment()
    version = solarian_version()
    name = pyproject_name(root)
    package = name.replace("-", "_")
    ctx = {
        "stamp": STAMP.format(version=version),
        "version": version,
        "name": name,
        "package": package,
        "short": name.removeprefix("solarian-"),
        "notes": NOTES,
    }

    def render(text: str) -> str:
        return env.from_string(text).render(**ctx)

    skills: dict[str, dict[str, bytes]] = {}
    for skill_dir in sorted((TEMPLATES / "skills" / kind).glob("*/")):
        if (skill_dir / "SKILL.md").is_file():
            skills[skill_dir.name] = _skill_files(skill_dir, skill_dir.name, render)

    if kind == "project":
        plugins = installed_plugins()
        for plugin in plugins:
            for skill_dir in plugin.skills:
                skill_name = f"{plugin.short}-{skill_dir.name}"
                skills[skill_name] = _skill_files(skill_dir, skill_name, lambda text: text)
        ctx["plugins"] = plugins
    else:
        ctx["groups"] = _entry_point_groups(_pyproject_text(root))

    ctx["skills"] = [
        {"name": skill, "description": frontmatter(files["SKILL.md"].decode()).get("description", "")}
        for skill, files in sorted(skills.items())
    ]

    files = {
        "AGENTS.md": env.get_template(f"{kind}/AGENTS.md.j2").render(**ctx).encode(),
        "CLAUDE.md": f"{ctx['stamp']}\n@AGENTS.md\n".encode(),
    }
    for skill, skill_files in skills.items():
        for rel, content in skill_files.items():
            for skill_root in SKILL_DIRS:
                files[f"{skill_root}/{skill}/{rel}"] = content
    return files


# ── Sync ──────────────────────────────────────────────────────────────


@dataclass
class SyncReport:
    written: list[str] = field(default_factory=list)
    removed: list[str] = field(default_factory=list)
    #: Managed files someone edited, or files Solarian did not write, left in place.
    conflicts: list[str] = field(default_factory=list)
    unchanged: int = 0
    notes_created: bool = False


def read_manifest(root: Path) -> dict:
    path = root / MANIFEST
    if not path.is_file():
        return {"solarian": None, "files": {}}
    return json.loads(path.read_text(encoding="utf-8"))


def _remove_empty_parents(path: Path, root: Path) -> None:
    for parent in path.parents:
        if parent == root or not parent.is_relative_to(root):
            return
        if any(parent.iterdir()):
            return
        parent.rmdir()


def sync_agent_files(root: Path, kind: str, force: bool = False, dry_run: bool = False) -> SyncReport:
    """Bring *root*'s agent files up to date with the installed Solarian and plugins.

    A file whose content no longer matches what the last sync wrote was edited
    by someone, and so is a file Solarian never wrote; both are reported as
    conflicts and left alone unless *force*. With *dry_run* nothing is written:
    the report says what a sync would do.
    """
    if kind not in KINDS:
        raise ValueError(f"kind is one of {KINDS}, not {kind!r}")
    root = root.resolve()
    report = SyncReport()
    recorded: dict[str, str] = read_manifest(root)["files"]
    manifest: dict[str, str] = {}

    for rel, content in desired_files(root, kind).items():
        path = root / rel
        if path.exists():
            current = path.read_bytes()
            if current == content:
                report.unchanged += 1
                manifest[rel] = _sha(content)
                continue
            if not force and recorded.get(rel) != _sha(current):
                report.conflicts.append(rel)
                if rel in recorded:
                    manifest[rel] = recorded[rel]
                continue
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        manifest[rel] = _sha(content)
        report.written.append(rel)

    for rel, digest in recorded.items():
        path = root / rel
        if rel in manifest or not path.is_file():
            continue
        if not force and _sha(path.read_bytes()) != digest:
            report.conflicts.append(rel)
            manifest[rel] = digest
            continue
        if not dry_run:
            path.unlink()
            _remove_empty_parents(path, root)
        report.removed.append(rel)

    notes = root / NOTES
    if not notes.exists():
        if not dry_run:
            notes.parent.mkdir(parents=True, exist_ok=True)
            notes.write_text((TEMPLATES / "NOTES.md").read_text(encoding="utf-8"), encoding="utf-8")
        report.notes_created = True

    if dry_run:
        return report
    (root / MANIFEST).write_text(
        json.dumps({"solarian": solarian_version(), "files": dict(sorted(manifest.items()))}, indent=2) + "\n",
        encoding="utf-8",
    )
    return report


def print_report(report: SyncReport) -> None:
    if report.written:
        print(f"Agent files: wrote {', '.join(summarize(report.written))}")
    if report.removed:
        print(f"Agent files: removed {', '.join(summarize(report.removed))}")
    if report.notes_created:
        print(f"Agent files: created {NOTES} for your own notes to agents")
    if report.conflicts:
        print("Agent files: left these alone because they were edited or not written by Solarian:")
        for rel in report.conflicts:
            print(f"  {rel}")
        print(f"  Move your changes into {NOTES}, then run `solarian agent sync --force`.")
    if not (report.written or report.removed or report.conflicts):
        print("Agent files: up to date")


def summarize(paths: list[str]) -> list[str]:
    """AGENTS.md, CLAUDE.md and one entry per skill, rather than every file."""
    seen: list[str] = []
    for rel in paths:
        parts = rel.split("/")
        label = f"skill {parts[2]}" if len(parts) > 3 and "/".join(parts[:2]) in SKILL_DIRS else rel
        if label not in seen:
            seen.append(label)
    return seen


# ── User-level bootstrap skill ────────────────────────────────────────


def install_bootstrap_skill(targets: list[str], force: bool = False) -> list[tuple[Path, str]]:
    """Copy the bootstrap skill into each target's user skill folder.

    Returns ``(folder, outcome)`` with outcome ``installed``, ``updated``,
    ``unchanged`` or ``skipped`` (a ``solarian`` skill Solarian did not install).
    """
    source = TEMPLATES / "bootstrap" / BOOTSTRAP_SKILL
    version = solarian_version()
    text = (source / "SKILL.md").read_text(encoding="utf-8")
    skill_md = re.sub(r"^(---\n.*?\n---\n)",
                      rf"\g<1><!-- installed by solarian {version}; `solarian agent install` updates it -->\n",
                      text, count=1, flags=re.S)
    results = []
    for target in targets:
        dest = USER_SKILL_DIRS[target] / BOOTSTRAP_SKILL
        existing = dest / "SKILL.md"
        if existing.is_file():
            current = existing.read_text(encoding="utf-8")
            if current == skill_md:
                results.append((dest, "unchanged"))
                continue
            if stamp_version(current) is None and not force:
                results.append((dest, "skipped"))
                continue
            outcome = "updated"
        else:
            outcome = "installed"
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(source, dest, ignore=shutil.ignore_patterns("__pycache__"))
        (dest / "SKILL.md").write_text(skill_md, encoding="utf-8")
        results.append((dest, outcome))
    return results


def default_targets() -> list[str]:
    """``agents`` always; ``claude`` when Claude Code has a folder in the home directory."""
    targets = ["agents"]
    if USER_SKILL_DIRS["claude"].parent.is_dir():
        targets.append("claude")
    return targets
